/**
 * Builds the HTML and plain-text body for an invoice email.
 * @param {{ invoice: Object, businessName: string, recipientName: string }} options
 * @returns {{ subject: string, html: string, text: string }}
 */
export function buildInvoiceEmailTemplate({ invoice, businessName, recipientName }) {
  const displayName = recipientName || invoice.customer?.name || 'Customer';
  const invoiceNumber = invoice.invoiceNumber || '—';
  const invoiceDate = invoice.invoiceDate || '—';
  const dueDate = invoice.dueDate || 'No due date';
  const netTotal = typeof invoice.netTotal === 'number' ? invoice.netTotal : invoice.grandTotal || 0;
  const formattedTotal = new Intl.NumberFormat('en-IN', {
    style: 'currency',
    currency: 'INR',
    minimumFractionDigits: 2
  }).format(netTotal);

  const subject = `Invoice ${invoiceNumber} from ${businessName} — ₹${netTotal.toFixed(2)}`;

  const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8"/>
  <meta name="viewport" content="width=device-width, initial-scale=1.0"/>
  <title>Invoice ${invoiceNumber}</title>
  <style>
    body { font-family: -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif; background: #f4f4f5; margin: 0; padding: 0; }
    .wrapper { max-width: 600px; margin: 32px auto; background: #ffffff; border-radius: 8px; overflow: hidden; box-shadow: 0 2px 8px rgba(0,0,0,.08); }
    .header { background: #1e2939; padding: 24px 32px; }
    .header h1 { color: #ffffff; font-size: 22px; margin: 0; }
    .header p { color: #94a3b8; font-size: 13px; margin: 4px 0 0; }
    .body { padding: 32px; }
    .body p { color: #374151; font-size: 15px; line-height: 1.6; }
    .invoice-box { background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 6px; padding: 20px 24px; margin: 24px 0; }
    .invoice-row { display: flex; justify-content: space-between; margin: 6px 0; font-size: 14px; color: #374151; }
    .invoice-row .label { color: #6b7280; }
    .total-row { border-top: 2px solid #1e2939; margin-top: 12px; padding-top: 12px; }
    .total-row .amount { font-size: 20px; font-weight: 700; color: #1e2939; }
    .footer { background: #f8fafc; border-top: 1px solid #e5e7eb; padding: 20px 32px; text-align: center; }
    .footer p { font-size: 12px; color: #9ca3af; margin: 4px 0; }
  </style>
</head>
<body>
  <div class="wrapper">
    <div class="header">
      <h1>${businessName}</h1>
      <p>Tax Invoice</p>
    </div>
    <div class="body">
      <p>Dear ${displayName},</p>
      <p>Please find your invoice details below. Kindly process the payment at your earliest convenience.</p>
      <div class="invoice-box">
        <div class="invoice-row">
          <span class="label">Invoice Number</span>
          <span><strong>${invoiceNumber}</strong></span>
        </div>
        <div class="invoice-row">
          <span class="label">Invoice Date</span>
          <span>${invoiceDate}</span>
        </div>
        <div class="invoice-row">
          <span class="label">Due Date</span>
          <span>${dueDate}</span>
        </div>
        <div class="invoice-row total-row">
          <span class="label">Total Amount Due</span>
          <span class="amount">${formattedTotal}</span>
        </div>
      </div>
      <p>If you have any questions about this invoice, please contact us.</p>
      <p>Thank you for your business!</p>
      <p>Regards,<br/><strong>${businessName}</strong></p>
    </div>
    <div class="footer">
      <p>This email was generated by BillGST — GST Invoicing for India</p>
      <p>If you did not expect this email, please disregard it.</p>
    </div>
  </div>
</body>
</html>`;

  const text = `Invoice from ${businessName}

Dear ${displayName},

Please find your invoice details below:

Invoice Number : ${invoiceNumber}
Invoice Date   : ${invoiceDate}
Due Date       : ${dueDate}
Amount Due     : ${formattedTotal}

Thank you for your business!

Regards,
${businessName}

---
Generated by BillGST
`;

  return { subject, html, text };
}
