import { db } from './database';

export const BACKUP_SCHEMA_VERSION = 1;

/**
 * Creates and downloads a JSON backup file containing all local IndexedDB data.
 */
export async function exportBackup() {
  try {
    const business = await db.business.toArray();
    const customers = await db.customers.toArray();
    const products = await db.products.toArray();
    const invoices = await db.invoices.toArray();
    const settings = await db.settings.toArray();

    const backupData = {
      app: 'BillGST',
      version: BACKUP_SCHEMA_VERSION,
      exportedAt: new Date().toISOString(),
      data: {
        business,
        customers,
        products,
        invoices,
        settings
      }
    };

    const jsonStr = JSON.stringify(backupData, null, 2);
    const blob = new Blob([jsonStr], { type: 'application/json' });
    const url = URL.createObjectURL(blob);

    const today = new Date().toISOString().slice(0, 10);
    const filename = `gst-invoice-backup-${today}.json`;

    const link = document.createElement('a');
    link.href = url;
    link.download = filename;
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
    URL.revokeObjectURL(url);

    return {
      success: true,
      counts: {
        invoices: invoices.length,
        customers: customers.length,
        products: products.length
      }
    };
  } catch (error) {
    console.error('Failed to export backup:', error);
    throw new Error('Failed to generate local backup file.');
  }
}

/**
 * Validates a parsed JSON backup object against expected structure.
 */
export function validateBackupFile(backup) {
  if (!backup || typeof backup !== 'object') {
    return { isValid: false, message: 'Invalid file: not a JSON object' };
  }

  if (backup.app !== 'BillGST') {
    return { isValid: false, message: 'Unrecognized backup file. This file was not generated by BillGST.' };
  }

  if (!backup.data || typeof backup.data !== 'object') {
    return { isValid: false, message: 'Corrupted backup file: missing data tables payload.' };
  }

  const { business, customers, products, invoices, settings } = backup.data;

  if (
    !Array.isArray(business) ||
    !Array.isArray(customers) ||
    !Array.isArray(products) ||
    !Array.isArray(invoices) ||
    !Array.isArray(settings)
  ) {
    return { isValid: false, message: 'Invalid backup structure: table datasets must be arrays.' };
  }

  return {
    isValid: true,
    metadata: {
      exportedAt: backup.exportedAt,
      version: backup.version,
      counts: {
        invoices: invoices.length,
        customers: customers.length,
        products: products.length
      }
    }
  };
}

/**
 * Imports validated backup data into IndexedDB.
 * Can mode: 'replace' (clears existing) or 'merge'.
 */
export async function importBackup(backupObject, mode = 'replace') {
  const validation = validateBackupFile(backupObject);
  if (!validation.isValid) {
    throw new Error(validation.message);
  }

  const { business, customers, products, invoices, settings } = backupObject.data;

  try {
    await db.transaction('rw', [db.business, db.customers, db.products, db.invoices, db.settings], async () => {
      if (mode === 'replace') {
        await db.business.clear();
        await db.customers.clear();
        await db.products.clear();
        await db.invoices.clear();
        await db.settings.clear();
      }

      if (business.length > 0) {
        await db.business.bulkPut(business);
      }
      if (customers.length > 0) {
        await db.customers.bulkPut(customers);
      }
      if (products.length > 0) {
        await db.products.bulkPut(products);
      }
      if (invoices.length > 0) {
        await db.invoices.bulkPut(invoices);
      }
      if (settings.length > 0) {
        await db.settings.bulkPut(settings);
      }
    });

    return {
      success: true,
      importedCounts: validation.metadata.counts
    };
  } catch (error) {
    console.error('Failed to import backup:', error);
    throw new Error('Database import failed. Your local storage may be locked or full.');
  }
}
